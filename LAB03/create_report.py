from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.units import cm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak

OUTPUT = "/home/doantruongson/Lab3/report/Lab3_Report.pdf"

doc = SimpleDocTemplate(
    OUTPUT,
    pagesize=A4,
    rightMargin=2*cm,
    leftMargin=2*cm,
    topMargin=2*cm,
    bottomMargin=2*cm
)

styles = getSampleStyleSheet()

title = ParagraphStyle(
    "CustomTitle",
    parent=styles["Title"],
    fontSize=23,
    alignment=TA_CENTER,
    textColor=colors.darkblue,
    spaceAfter=20
)

heading = ParagraphStyle(
    "CustomHeading",
    parent=styles["Heading2"],
    textColor=colors.darkblue,
    spaceBefore=12,
    spaceAfter=8
)

body = styles["BodyText"]

story = []

# COVER PAGE
story.append(Spacer(1, 4*cm))
story.append(Paragraph("LAB-03 REPORT", title))
story.append(Paragraph(
    "Embedded Linux Debugging and Real-Time Performance Testing",
    ParagraphStyle("Subtitle", parent=body, alignment=TA_CENTER, fontSize=13)
))
story.append(Spacer(1, 3*cm))
story.append(Paragraph("<b>Student:</b> Doan Truong Son", body))
story.append(Paragraph("<b>Course:</b> Embedded Linux", body))
story.append(Paragraph("<b>Operating System:</b> Ubuntu Linux", body))
story.append(Paragraph("<b>Platform:</b> ARM QEMU / Cortex-A9", body))
story.append(Spacer(1, 3*cm))
story.append(Paragraph(
    "2026",
    ParagraphStyle("Year", parent=body, alignment=TA_CENTER)
))
story.append(PageBreak())

# 1. INTRODUCTION
story.append(Paragraph("1. INTRODUCTION", heading))
story.append(Paragraph(
    "This laboratory focuses on Embedded Linux debugging, memory error "
    "detection, system call tracing, application performance analysis, "
    "and real-time scheduling evaluation.",
    body
))

# 2. OBJECTIVES
story.append(Paragraph("2. OBJECTIVES", heading))
for item in [
    "Prepare an ARM debugging environment using QEMU.",
    "Analyze memory errors using Valgrind.",
    "Trace system calls using strace.",
    "Measure application performance using perf.",
    "Evaluate scheduling latency using cyclictest.",
    "Compare Standard Linux and PREEMPT_RT kernels."
]:
    story.append(Paragraph("- " + item, body))

# 3. ENVIRONMENT
story.append(Paragraph("3. EXPERIMENTAL ENVIRONMENT", heading))

environment = [
    ["Component", "Description"],
    ["Host OS", "Ubuntu Linux"],
    ["Architecture", "x86_64"],
    ["ARM Platform", "Cortex-A9"],
    ["Emulator", "QEMU"],
    ["Compiler", "GCC / arm-linux-gnueabihf-gcc"],
    ["Memory Analysis", "Valgrind"],
    ["Tracing", "strace"],
    ["Performance", "perf"],
    ["Real-time Test", "cyclictest"],
    ["RT Kernel", "7.0.0-38-realtime"]
]

table = Table(environment, colWidths=[5*cm, 10*cm])
table.setStyle(TableStyle([
    ("BACKGROUND", (0,0), (-1,0), colors.lightblue),
    ("GRID", (0,0), (-1,-1), 0.5, colors.grey),
    ("FONTNAME", (0,0), (-1,0), "Helvetica-Bold"),
    ("PADDING", (0,0), (-1,-1), 7)
]))
story.append(table)

# 4. VALGRIND
story.append(Paragraph("4. MEMORY ERROR DETECTION - VALGRIND", heading))
story.append(Paragraph(
    "Valgrind was used to analyze memory errors in buggy_app_host. "
    "The application contains an out-of-bounds read in process_data(), "
    "a use-after-free in create_message(), and signed integer overflow "
    "in calculate().",
    body
))
story.append(Paragraph(
    "Valgrind reported 47 errors from 8 contexts, including invalid and "
    "uninitialized memory accesses. The heap summary showed two allocations "
    "and two frees, with no outstanding heap blocks at exit.",
    body
))

# 5. STRACE
story.append(Paragraph("5. SYSTEM CALL TRACING - STRACE", heading))
story.append(Paragraph(
    "The strace utility was used to monitor system calls generated by "
    "the application. The trace included execve, openat, read, write, "
    "mmap, munmap, close and exit_group.",
    body
))
story.append(Paragraph("Result: logs/strace_log.txt", body))

# 6. PERF
story.append(Paragraph("6. PERFORMANCE ANALYSIS - PERF", heading))

perf = [
    ["Metric", "Result"],
    ["Task Clock", "0.54 ms"],
    ["Context Switches", "0"],
    ["CPU Migrations", "0"],
    ["Page Faults", "62"],
    ["Elapsed Time", "1.69 ms"]
]

table = Table(perf, colWidths=[7*cm, 7*cm])
table.setStyle(TableStyle([
    ("BACKGROUND", (0,0), (-1,0), colors.lightblue),
    ("GRID", (0,0), (-1,-1), 0.5, colors.grey),
    ("FONTNAME", (0,0), (-1,0), "Helvetica-Bold"),
    ("PADDING", (0,0), (-1,-1), 7)
]))
story.append(table)
story.append(Paragraph(
    "The performance results are saved in logs/perf_stat.txt. "
    "This measurement was performed on the Ubuntu host.",
    body
))

# 7. CYCLICTEST
story.append(Paragraph("7. REAL-TIME PERFORMANCE TESTING", heading))
story.append(Paragraph(
    "Cyclictest was executed using FIFO scheduling, priority 80, "
    "a 1000 microsecond interval and 10000 iterations.",
    body
))

cyclic = [
    ["Metric", "Standard", "PREEMPT_RT"],
    ["Minimum Latency", "2 us", "2 us"],
    ["Average Latency", "3 us", "3 us"],
    ["Maximum Latency", "117 us", "93 us"],
    ["Iterations", "10000", "10000"]
]

table = Table(cyclic, colWidths=[5*cm, 5*cm, 5*cm])
table.setStyle(TableStyle([
    ("BACKGROUND", (0,0), (-1,0), colors.lightblue),
    ("GRID", (0,0), (-1,-1), 0.5, colors.grey),
    ("FONTNAME", (0,0), (-1,0), "Helvetica-Bold"),
    ("PADDING", (0,0), (-1,-1), 7)
]))
story.append(table)

story.append(Spacer(1, 10))
story.append(Paragraph(
    "The PREEMPT_RT kernel reduced maximum latency from 117 us "
    "to 93 us, an improvement of approximately 20.5 percent. "
    "Minimum and average latency remained unchanged.",
    body
))
story.append(Paragraph(
    "The real-time kernel configuration was verified with "
    "CONFIG_PREEMPT_RT=y.",
    body
))

# 8. LIMITATIONS
story.append(Paragraph("8. LIMITATIONS", heading))
story.append(Paragraph(
    "Section A.2 (GDB Remote Debugging) was intentionally skipped. "
    "The perf measurement and cyclictest experiments were performed "
    "on the Ubuntu host. Results represent individual test runs and "
    "may vary under different system loads.",
    body
))

# 9. CONCLUSION
story.append(Paragraph("9. CONCLUSION", heading))
story.append(Paragraph(
    "This laboratory demonstrated memory debugging with Valgrind, "
    "system call tracing with strace, performance measurement with perf, "
    "and real-time latency evaluation with cyclictest. The recorded "
    "results showed that PREEMPT_RT achieved a lower maximum scheduling "
    "latency than the Standard Linux kernel.",
    body
))

doc.build(story)

print("======================================")
print("LAB-03 REPORT CREATED SUCCESSFULLY")
print("Location:", OUTPUT)
print("======================================")
